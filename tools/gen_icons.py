"""Copies the Android toolbar icons into the Windows app, so both versions use the same icons.

Reads android/app/src/main/res/drawable/ic_*.xml (simple filled vector paths) and writes
refpad/ui/icon_paths.py. Run again after changing an Android icon:

    py -3.12 tools/gen_icons.py
"""
import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "android/app/src/main/res/drawable"
OUT = ROOT / "refpad/ui/icon_paths.py"
A = "{http://schemas.android.com/apk/res/android}"
SKIP = {"ic_launcher_foreground", "ic_launcher_monochrome", "ic_stat_refpad"}


def main():
    icons = {}
    for f in sorted(SRC.glob("ic_*.xml")):
        if f.stem in SKIP:
            continue
        root = ET.parse(f).getroot()
        vw = float(root.get(A + "viewportWidth"))
        vh = float(root.get(A + "viewportHeight"))
        paths = []
        for p in root.iter("path"):
            color = p.get(A + "fillColor", "#FFFFFFFF")
            alpha = int(color[1:3], 16) / 255 if len(color) == 9 else 1.0
            paths.append((p.get(A + "pathData"), round(alpha, 3)))
        icons[f.stem[3:]] = (vw, vh, paths)

    lines = ['"""Generated by tools/gen_icons.py from the Android icons. Do not edit by hand."""', "", "ICONS = {"]
    for name, (vw, vh, paths) in icons.items():
        lines.append(f"    {name!r}: ({vw:g}, {vh:g}, [")
        for d, alpha in paths:
            lines.append(f"        ({re.sub(r'\s+', ' ', d)!r}, {alpha}),")
        lines.append("    ]),")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(icons)} icons to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
